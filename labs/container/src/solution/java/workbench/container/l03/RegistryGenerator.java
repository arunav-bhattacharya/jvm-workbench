package workbench.container.l03;

import java.util.Collection;
import java.util.List;
import java.util.stream.Collectors;

/**
 * The build-time half of the container: it does the graph work now and writes a Java class that
 * wires the same components with plain {@code new} calls when it runs.
 */
public final class RegistryGenerator {
    private RegistryGenerator() {}

    public static String generate(String packageName, String className, Collection<Class<?>> components) {
        BeanGraph graph = new BeanGraph(components);
        List<Class<?>> order = graph.creationOrder();       // at build time: a cycle fails the build, not the start
        StringBuilder out = new StringBuilder(header(packageName, className, order));
        for (Class<?> c : order) {
            if (Container.scopeOf(c) == Scope.SINGLETON) {
                // 1. the holder idiom: the JVM runs this initializer on first use, once, under the class init lock
                out.append("    private static final class ").append(holder(c)).append(" {\n")
                        .append("        static final ").append(beanType(c)).append(" INSTANCE = ")
                        .append(newExpression(graph, c)).append(";\n    }\n\n");
            } else {
                // 2. a prototype: a plain factory method, a new object on every call
                out.append("    private static ").append(beanType(c)).append(" ").append(factory(c)).append("() {\n")
                        .append("        return ").append(newExpression(graph, c)).append(";\n    }\n\n");
            }
        }
        // 3. get: one identity check per bound type, no map, no reflection
        out.append("    @Override\n    public <T> T get(Class<T> type) {\n");
        for (Class<?> c : order) {
            for (Class<?> type : boundTypes(graph, c)) {
                out.append("        if (type == ").append(type.getCanonicalName()).append(".class) return type.cast(")
                        .append(reference(c)).append(");\n");
            }
        }
        out.append("        throw new ContainerException(\"No component provides \" + type.getSimpleName());\n    }\n\n");
        return out.append(footer(order)).toString();
    }

    // ---- given helpers: everything below is the same in src/main ----------------------------------

    /** Package, imports, the class line, the shared Interception and the creation order. */
    static String header(String packageName, String className, List<Class<?>> order) {
        return "package " + packageName + ";\n\n"
                + "import workbench.container.l03.*;\n\n"
                + "/** Generated by RegistryGenerator from " + order.size() + " components. Do not edit. */\n"
                + "@SuppressWarnings(\"unchecked\")   // Interception.chain takes Class<? extends Throwable>...\n"
                + "public final class " + className + " implements Registry {\n"
                + "    static final Interception INTERCEPTION = new Interception();\n"
                + "    private static final java.util.List<Class<?>> ORDER = java.util.List.of(\n"
                + order.stream().map(c -> "            " + c.getCanonicalName() + ".class").collect(Collectors.joining(",\n"))
                + ");\n\n";
    }

    /** creationOrder(), callLog(), the generated proxy classes and the closing brace. */
    static String footer(List<Class<?>> order) {
        StringBuilder out = new StringBuilder()
                .append("    @Override\n    public java.util.List<Class<?>> creationOrder() {\n        return ORDER;\n    }\n\n")
                .append("    @Override\n    public CallLog callLog() {\n        return INTERCEPTION.getLog();\n    }\n\n");
        for (Class<?> c : order) out.append(ProxySource.emit(c));
        return out.append("}\n").toString();
    }

    /** The name of a singleton's holder class: {@code FxRates_Holder}. */
    static String holder(Class<?> component) {
        return component.getSimpleName() + "_Holder";
    }

    /** The name of a prototype's factory method: {@code new_PaymentAttempt}. */
    static String factory(Class<?> component) {
        return "new_" + component.getSimpleName();
    }

    /** The static type of the bean: the component's class, or its generated proxy class. */
    static String beanType(Class<?> component) {
        String proxy = ProxySource.className(component);
        return proxy != null ? proxy : component.getCanonicalName();
    }

    /** Java code for the bean: {@code FxRates_Holder.INSTANCE} for a singleton, {@code new_PaymentAttempt()} for a prototype. */
    static String reference(Class<?> component) {
        return Container.scopeOf(component) == Scope.SINGLETON ? holder(component) + ".INSTANCE" : factory(component) + "()";
    }

    /** Java code that builds a new bean, its dependencies passed in: {@code new FeeCalculator(FxRates_Holder.INSTANCE)}. */
    static String newExpression(BeanGraph graph, Class<?> component) {
        Class<?>[] params = Constructors.pick(component).getParameterTypes();
        List<Class<?>> deps = graph.dependenciesOf(component);
        StringBuilder args = new StringBuilder();
        for (int i = 0; i < deps.size(); i++) {
            Class<?> dep = deps.get(i);
            if (!boundTypes(graph, dep).contains(params[i])) {
                throw new ContainerException(component.getSimpleName() + " needs " + params[i].getSimpleName()
                        + ", but that component is behind a proxy; depend on one of its interfaces");
            }
            args.append(i == 0 ? "" : ", ").append(reference(dep));
        }
        String proxy = ProxySource.className(component);
        String call;
        if (proxy == null) call = "new " + component.getCanonicalName() + "(" + args + ")";
        else if (component.getInterfaces().length > 0) {
            call = "new " + proxy + "(new " + component.getCanonicalName() + "(" + args + "))";   // forwarder around a target
        } else {
            call = "new " + proxy + "(" + args + ")";                                             // the subclass is the bean
        }
        if (Constructors.pick(component).getExceptionTypes().length == 0) return call;
        // a static initializer can't throw a checked exception: wrap it, as the reflective container does
        return "Registry.construct(\"" + component.getSimpleName() + "\", () -> " + call + ")";
    }

    /** The types {@code get} answers for this component. A forwarding proxy is not an instance of the class. */
    static List<Class<?>> boundTypes(BeanGraph graph, Class<?> component) {
        boolean forwarded = ProxySource.className(component) != null && component.getInterfaces().length > 0;
        return graph.typesBoundTo(component).stream().filter(t -> !(forwarded && t == component)).toList();
    }
}
