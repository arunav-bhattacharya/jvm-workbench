/** The moving company: registered in src/main/resources/workbench/ksp/l03/SymbolProcessorProvider. */
class LabelProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        LabelProcessor(environment.codeGenerator, environment.logger)
}

class LabelProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
) : SymbolProcessor {

    // Given code: the KSP 2.3.14 opt-in, as in lesson 2.
    override val apiFeatures: ApiFeatures = buildApiFeatures {
        enableBackingFields = true
        enableContextParameters = true
    }

    // Given code: while the lab is unfinished this logs a warning and generates nothing,
    // so a real build with -Pmine=l03 still runs.
    override fun process(resolver: Resolver): List<KSAnnotated> = try {
        processLabels(resolver)
    } catch (e: NotImplementedError) {
        logger.warn("l03 not done yet: ${e.message?.substringAfter("not implemented: ")}")
        emptyList()
    }

    /** Given code: moves 1, 2 and 4 as you wrote them in lesson 2. Move 3 calls your functions below. */
    fun processLabels(resolver: Resolver): List<KSAnnotated> {
        // 1. Find
        for (symbol in resolver.getSymbolsWithAnnotation("workbench.ksp.annotations.Label")) {
            // 2. Check
            if (symbol !is KSClassDeclaration || symbol.classKind != ClassKind.CLASS) {
                logger.error("@Label goes on a class, but ${describe(symbol)}", symbol)
                continue
            }
            // 3. Read: your functions
            val shape = shapeOf(symbol)
            val room = roomOf(symbol)
            val handling = handlingOf(symbol)
            // 4. Write: one new file per class, redone when that class's file changes
            writeLabel(symbol, labelSource(symbol, shape, room, handling))
        }
        return emptyList()
    }

    /** Given: "Shape is an interface", "Truck is an object". */
    private fun describe(symbol: KSAnnotated): String {
        if (symbol !is KSClassDeclaration) return "${(symbol as? KSDeclaration)?.simpleName?.asString()} is not a class"
        val kind = symbol.classKind.name.lowercase().replace('_', ' ')
        return "${symbol.simpleName.asString()} is ${if (kind.first() in "aeiou") "an" else "a"} $kind"
    }

    private fun writeLabel(cls: KSClassDeclaration, source: String) {
        codeGenerator.createNewFile(
            Dependencies(aggregating = false, cls.containingFile!!),
            cls.packageName.asString(),
            "${cls.simpleName.asString()}Label",
        ).use { it.write(source.toByteArray()) }
    }
}

/** Given code: the text of the label file. Lesson 4 hands this job to KotlinPoet. */
fun labelSource(cls: KSClassDeclaration, shape: String, room: String?, handling: String?): String {
    val name = cls.simpleName.asString()
    val lines = listOfNotNull(
        "    const val SHAPE: String = ${literal(shape)}",
        room?.let { "    const val ROOM: String = ${literal(it)}" },
        handling?.let { "    const val HANDLING: String = ${literal(it)}" },
    )
    return buildString {
        appendLine("// Generated by LabelProcessor from $name. Do not edit.")
        appendLine("package ${cls.packageName.asString()}")
        appendLine()
        appendLine("object ${name}Label {")
        lines.forEach(::appendLine)
        appendLine("}")
    }
}

/** Given code: a Kotlin string literal, with the characters that would break it escaped. */
private fun literal(text: String): String =
    "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""

/**
 * Given code: the annotation on [node] whose fully qualified name is [qualifiedName], or null. It compares the
 * short name first, which costs nothing, and resolves the annotation's type only when the short name matches,
 * because a short name such as `Room` could come from any package.
 */
fun annotationNamed(node: KSAnnotated, qualifiedName: String): KSAnnotation? =
    node.annotations.firstOrNull { annotation ->
        annotation.shortName.asString() == qualifiedName.substringAfterLast('.') &&
            annotation.annotationType.resolve().declaration.qualifiedName?.asString() == qualifiedName
    }

