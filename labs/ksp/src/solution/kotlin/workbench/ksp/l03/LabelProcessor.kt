/**
 * A type as a label prints it: `String`, `String?`, `List<String>`, `Map<String, List<Int?>>?`, `List<*>`, and
 * `String!` for a Java type whose nullability Kotlin doesn't know (a platform type). Type arguments are printed
 * the same way, all the way down.
 */
fun typeText(ref: KSTypeReference): String {
    val type: KSType = ref.resolve() // the expensive step: work out what the written name refers to
    val name = type.declaration.simpleName.asString()
    val arguments = if (type.arguments.isEmpty()) "" else type.arguments.joinToString(", ", "<", ">") { arg ->
        when (arg.variance) {
            Variance.STAR -> "*" // a star has no type: arg.type is null
            Variance.COVARIANT -> "out " + typeText(arg.type!!)
            Variance.CONTRAVARIANT -> "in " + typeText(arg.type!!)
            Variance.INVARIANT -> typeText(arg.type!!)
        }
    }
    val mark = when (type.nullability) {
        Nullability.NULLABLE -> "?"
        Nullability.PLATFORM -> "!"
        Nullability.NOT_NULL -> ""
    }
    return name + arguments + mark
}

/**
 * The typed shape of a class: its name and its constructor's parameters, for example
 * `Plant(kind: String, potLitres: Double, waterEveryDays: Int = ...)`. A parameter with a default ends in
 * ` = ...` (KSP knows a default exists, never what it is), and one marked @Fragile starts with `@Fragile `.
 * A Java class has no primary constructor, so use the first constructor KSP finds.
 */
fun shapeOf(cls: KSClassDeclaration): String {
    val constructor = cls.primaryConstructor ?: cls.getConstructors().firstOrNull()
    val parameters = constructor?.parameters.orEmpty().joinToString(", ") { parameter ->
        val fragile = if (annotationNamed(parameter, "workbench.ksp.annotations.Fragile") != null) "@Fragile " else ""
        val default = if (parameter.hasDefault) " = ..." else ""
        "$fragile${parameter.name!!.asString()}: ${typeText(parameter.type)}$default"
    }
    return "${cls.simpleName.asString()}($parameters)"
}

/** The room written on `@Room("kitchen")` (its `name` argument), or null when the class has no @Room. */
fun roomOf(cls: KSClassDeclaration): String? {
    val room = annotationNamed(cls, "workbench.ksp.annotations.Room") ?: return null
    return room.arguments.first { it.name?.asString() == "name" }.value as String
}

/**
 * The @Handling instructions, always in the order care, stackable, packWith, for example
 * `care=UPRIGHT, stackable=true (default), packWith=Lamp`; null when the class has no @Handling. An argument
 * the source didn't write gets ` (default)` after its value.
 */
fun handlingOf(cls: KSClassDeclaration): String? {
    val handling = annotationNamed(cls, "workbench.ksp.annotations.l03.Handling") ?: return null
    // look arguments up by name: KSP lists the written ones first and the defaults after them
    fun argument(name: String): KSValueArgument = handling.arguments.first { it.name?.asString() == name }
    fun default(arg: KSValueArgument) = if (arg.isDefault()) " (default)" else ""

    val care = argument("care")           // an enum value arrives as its entry's declaration
    val stackable = argument("stackable") // a Boolean arrives as a Boolean
    val packWith = argument("packWith")   // a class (KClass) arrives as a KSType
    val careText = (care.value as KSClassDeclaration).simpleName.asString()
    val packText = (packWith.value as KSType).declaration.simpleName.asString()
    return "care=$careText${default(care)}, stackable=${stackable.value}${default(stackable)}, " +
        "packWith=$packText${default(packWith)}"
}
