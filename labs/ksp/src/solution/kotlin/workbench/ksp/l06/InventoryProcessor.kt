// Lesson 6, given code (the same in src/main and src/solution): lesson 2's InventoryProcessor, copied into this
// package and rewritten with KotlinPoet. It writes the same card, logs each round (so you can watch it pick up
// the receipts that ReceiptProcessor wrote in the round before) and never writes a card twice.

/** Registered in workbench/ksp/l06/SymbolProcessorProvider, on the line after ReceiptProcessorProvider. */
class InventoryProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        InventoryProcessor(environment.codeGenerator, environment.logger)
}

/**
 * For each class annotated [Inventory], generates `fun <Name>.inventoryCard(): String` in `<Name>InventoryCard.kt`, returning
 * for example `Lamp: name=desk lamp, bulbs=1, shade=null`. A card needs property names, never types, so this
 * processor sets nothing aside.
 */
class InventoryProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
) : SymbolProcessor {

    override val apiFeatures: ApiFeatures = buildApiFeatures {
        enableBackingFields = true
        enableContextParameters = true
    }

    private var round = 0

    /** Classes that already have a card. A symbol another processor set aside comes back in every processor's
     * lookup, for every annotation it carries, and writing the same file twice fails the build. */
    private val carded = mutableSetOf<String>()

    override fun process(resolver: Resolver): List<KSAnnotated> {
        round++
        val written = mutableListOf<String>()
        for (symbol in resolver.getSymbolsWithAnnotation(Inventory::class.qualifiedName!!)) {
            if (symbol !is KSClassDeclaration || symbol.classKind != ClassKind.CLASS) {
                logger.error("@Inventory goes on a class", symbol)
                continue
            }
            val cls: KSClassDeclaration = symbol
            if (!carded.add(cls.qualifiedName!!.asString())) continue
            cardFile(cls).writeTo(codeGenerator, aggregating = false)
            written += cls.simpleName.asString()
        }
        logger.warn("[cards] round $round: wrote cards for $written")
        return emptyList()
    }
}

/** `Lamp: name=desk lamp, bulbs=1, shade=null`: the class name, then each constructor property and its value. */
fun cardFile(cls: KSClassDeclaration): FileSpec {
    val name = cls.simpleName.asString()
    val props = cls.primaryConstructor?.parameters.orEmpty().filter { it.isVal || it.isVar }.map { it.name!!.asString() }
    val template = "$name: " + props.joinToString(", ") { "$it=\${$it}" }
    return FileSpec.builder(ClassName(cls.packageName.asString(), "${name}InventoryCard"))
        .addFileComment("Generated by InventoryProcessor from %L. Do not edit.", name)
        .addFunction(
            FunSpec.builder("inventoryCard")
                .receiver(cls.toClassName())
                .returns(STRING)
                .addStatement("return %P", template)
                .addOriginatingKSFile(cls.containingFile!!)
                .build(),
        )
        .build()
}
