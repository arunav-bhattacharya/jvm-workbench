package workbench.ksp.l01

import com.google.devtools.ksp.ApiFeatures
import com.google.devtools.ksp.buildApiFeatures
import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.ClassKind
import com.google.devtools.ksp.symbol.KSAnnotated
import com.google.devtools.ksp.symbol.KSClassDeclaration

// Given code, ready-made: you don't need to read it yet. It is the @Inventory card processor that lesson 2 has
// you write yourself, packed into one function. This lesson's tests and GeneratedCardDemo run it in memory; the
// real build (./gradlew :ksp:app:kspL01Kotlin) runs lesson 2's copy, named in labs/ksp/app/src/l01/processors.txt.

class ReadyMadeInventoryProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        ReadyMadeInventoryProcessor(environment.codeGenerator, environment.logger)
}

class ReadyMadeInventoryProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
) : SymbolProcessor {

    override val apiFeatures: ApiFeatures = buildApiFeatures {
        enableBackingFields = true
        enableContextParameters = true
    }

    override fun process(resolver: Resolver): List<KSAnnotated> {
        for (symbol in resolver.getSymbolsWithAnnotation("workbench.ksp.annotations.Inventory")) {
            if (symbol !is KSClassDeclaration || symbol.classKind != ClassKind.CLASS) {
                logger.error("@Inventory goes on a class", symbol)
                continue
            }
            // read the label: the names of the primary constructor's properties, in order
            val name = symbol.simpleName.asString()
            val pairs = symbol.primaryConstructor?.parameters.orEmpty()
                .filter { it.isVal || it.isVar }
                .joinToString(", ") { "${it.name!!.asString()}=\$${it.name!!.asString()}" }
            // write a new card next to the class
            val source = """
                |// Generated by InventoryProcessor from $name. Do not edit.
                |package ${symbol.packageName.asString()}
                |
                |fun $name.inventoryCard(): String =
                |    "$name: $pairs"
                |""".trimMargin()
            codeGenerator.createNewFile(
                Dependencies(aggregating = false, symbol.containingFile!!),
                symbol.packageName.asString(),
                "${name}InventoryCard",
            ).use { it.write(source.toByteArray()) }
        }
        return emptyList()
    }
}
