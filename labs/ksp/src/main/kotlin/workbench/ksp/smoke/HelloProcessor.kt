// Smoke example (keep or delete). It proves the pipeline: kctfork tests, a demo, and the real build in :ksp:app.
// It is complete in src/main too, so `test` and `solutionTest` both pass on a fresh checkout.

/** KSP creates the processor through this provider. Registered in workbench/ksp/smoke/SymbolProcessorProvider. */
class HelloProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        HelloProcessor(environment.codeGenerator, environment.logger)
}

/** For each class annotated [Hello], generates `fun helloFrom<ClassName>(): String` in `<ClassName>Hello.kt`. */
class HelloProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
) : SymbolProcessor {

    // KSP 2.3.14 asks each processor which newer API behaviours it accepts. Without this it prints three
    // "i: [ksp] Processor ... has not opted in for upcoming features yet" notes on every run.
    override val apiFeatures: ApiFeatures = buildApiFeatures {
        enableBackingFields = true
        enableContextParameters = true
    }

    override fun process(resolver: Resolver): List<KSAnnotated> {
        // 1. Find: everything annotated @Hello in this round
        val symbols = resolver.getSymbolsWithAnnotation(Hello::class.qualifiedName!!).toList()
        // symbols whose types can't be resolved yet wait for the next round (KSP 2.3.14 deprecates the
        // validate() overload without apiFeatures; SymbolProcessor has an apiFeatures property for it)
        val (ready, later) = symbols.partition { it.validate(apiFeatures = apiFeatures) }
        for (symbol in ready) {
            // 2. Check: only classes, with an error on the exact symbol otherwise
            if (symbol !is KSClassDeclaration || symbol.classKind != ClassKind.CLASS) {
                logger.error("@Hello goes on a class, but ${describe(symbol)}", symbol)
                continue
            }
            // 3. Read and 4. Write: one file per class, rebuilt only when that class's file changes
            helloFile(symbol).writeTo(codeGenerator, Dependencies(aggregating = false, symbol.containingFile!!))
        }
        return later
    }

    /** "Shape is an interface", "Config is an object". */
    private fun describe(symbol: KSAnnotated): String {
        if (symbol !is KSClassDeclaration) return "$symbol is not a class"
        val kind = symbol.classKind.name.lowercase().replace('_', ' ')
        return "${symbol.simpleName.asString()} is ${if (kind.first() in "aeiou") "an" else "a"} $kind"
    }
}

/** The generated file for one class: `<package>/<ClassName>Hello.kt` with `fun helloFrom<ClassName>()`. */
fun helloFile(cls: KSClassDeclaration): FileSpec {
    val name = cls.simpleName.asString()
    return FileSpec.builder(cls.packageName.asString(), "${name}Hello")
        .addFileComment("Generated by HelloProcessor from %L. Do not edit.", name)
        .addFunction(
            FunSpec.builder("helloFrom$name")
                .returns(STRING)
                .addStatement("return %S", "Hello from $name")
                .build(),
        )
        .build()
}
