// Lesson 2: your first processor. For each class with the sticky note @Inventory it writes a new file,
// <ClassName>InventoryCard.kt, next to the class, holding `fun <ClassName>.inventoryCard(): String`.
// The card is the class name, a colon, then name=value for each primary constructor property:
//     Lamp: name=desk lamp, bulbs=1, shade=null

/**
 * The moving company: KSP finds this class through the services file
 * (src/main/resources/workbench/ksp/l02/SymbolProcessorProvider, one line) and calls [create] once per build.
 */
class InventoryProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        InventoryProcessor(environment.codeGenerator, environment.logger)
}

