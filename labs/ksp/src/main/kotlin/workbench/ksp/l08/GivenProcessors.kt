/** KSP creates the card processor through this provider. Registered in workbench/ksp/l08/SymbolProcessorProvider. */
class InventoryProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        InventoryProcessor(environment.codeGenerator, environment.logger)
}

/** For each class annotated @Inventory: `fun Lamp.inventoryCard(): String` in `LampInventoryCard.kt`. */
class InventoryProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
) : SymbolProcessor {

    override val apiFeatures: ApiFeatures = buildApiFeatures {
        enableBackingFields = true
        enableContextParameters = true
    }

    override fun process(resolver: Resolver): List<KSAnnotated> {
        for (symbol in resolver.getSymbolsWithAnnotation(Inventory::class.qualifiedName!!)) {      // 1. Find
            if (symbol !is KSClassDeclaration || symbol.classKind != ClassKind.CLASS) {             // 2. Check
                logger.error("@Inventory goes on a class, but ${describe(symbol)}", symbol)
                continue
            }
            inventoryCardFile(symbol)                                                               // 3. Read
                .writeTo(codeGenerator, Dependencies(aggregating = false, symbol.containingFile!!))  // 4. Write
        }
        return emptyList()
    }
}

/** `Lamp: name=desk lamp, bulbs=1, shade=null`: the class name, then the primary constructor's properties. */
fun inventoryCardFile(cls: KSClassDeclaration): FileSpec {
    val name = cls.simpleName.asString()
    val properties = cls.primaryConstructor?.parameters.orEmpty().filter { it.isVal || it.isVar }
        .map { it.name!!.asString() }
    val template = "$name: " + properties.joinToString(", ") { "$it=\${$it}" }
    return FileSpec.builder(cls.packageName.asString(), "${name}InventoryCard")
        .addFileComment("Generated by InventoryProcessor from %L. Do not edit.", name)
        .addFunction(
            FunSpec.builder("inventoryCard")
                .receiver(cls.toClassName())
                .returns(STRING)
                .addStatement("return %L", "\"$template\"")
                .build(),
        )
        .build()
}

/** KSP creates the builder processor through this provider. */
class BuilderProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        BuilderProcessor(environment.codeGenerator, environment.logger)
}

/**
 * For each class annotated @Builder: `LampBuilder`, with one setter per primary constructor parameter and
 * `build()`. It reports every problem in one build, each on the declaration's own line.
 */
class BuilderProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
    private val typeOf: (KSTypeReference) -> TypeName = { it.toTypeName() },
) : SymbolProcessor {

    override val apiFeatures: ApiFeatures = buildApiFeatures {
        enableBackingFields = true
        enableContextParameters = true
    }

    override fun process(resolver: Resolver): List<KSAnnotated> {
        val (ready, later) = resolver.getSymbolsWithAnnotation(Builder::class.qualifiedName!!).toList()  // 1. Find
            .partition { it.validate(apiFeatures = apiFeatures) }
        for (symbol in ready) {
            val cls = checked(symbol) ?: continue                                                       // 2. Check
            builderFile(cls, typeOf)                                                                    // 3. Read
                .writeTo(codeGenerator, Dependencies(aggregating = false, cls.containingFile!!))         // 4. Write
        }
        return later
    }

    /** Check before you read: the class, or null after an error on the exact symbol. */
    private fun checked(symbol: KSAnnotated): KSClassDeclaration? {
        if (symbol !is KSClassDeclaration || symbol.classKind != ClassKind.CLASS) {
            logger.error("@Builder goes on a class, but ${describe(symbol)}", symbol)
            return null
        }
        val name = symbol.simpleName.asString()
        val constructor = symbol.primaryConstructor
        if (constructor == null) {
            logger.error("@Builder needs a primary constructor, and $name has none. Add one: class $name(val ...)", symbol)
            return null
        }
        if (constructor.isPrivate()) {
            logger.error("${name}Builder can't call $name's private constructor. Make the constructor public or internal.", symbol)
            return null
        }
        return symbol
    }
}

/**
 * The builder for one class. A nullable parameter starts as null; any other parameter must be set before
 * `build()`. (KSP tells you a parameter has a default, never what it is, so this small builder doesn't use
 * defaults.) [typeOf] turns a parameter's type into KotlinPoet's TypeName; the lesson's demo passes a broken one.
 */
fun builderFile(cls: KSClassDeclaration, typeOf: (KSTypeReference) -> TypeName = { it.toTypeName() }): FileSpec {
    val target = cls.toClassName()
    val builder = ClassName(target.packageName, "${target.simpleName}Builder")
    val parameters = cls.primaryConstructor!!.parameters.map { it.name!!.asString() to typeOf(it.type) }
    val type = TypeSpec.classBuilder(builder)
    for ((name, typeName) in parameters) {
        type.addProperty(
            PropertySpec.builder(name, typeName.copy(nullable = true), KModifier.PRIVATE).mutable().initializer("null").build(),
        )
    }
    for ((name, typeName) in parameters) {
        type.addFunction(
            FunSpec.builder(name).addParameter(name, typeName).returns(builder)
                .addStatement("return apply { this.%N = %N }", name, name).build(),
        )
    }
    val arguments = parameters.map { (name, typeName) ->
        if (typeName.isNullable) CodeBlock.of("%N = %N", name, name)
        else CodeBlock.of("%N = %N ?: error(%S)", name, name, "${builder.simpleName} needs $name")
    }
    type.addFunction(
        FunSpec.builder("build").returns(target)
            .addStatement("return %T(\n⇥%L,\n⇤)", target, arguments.joinToCode(",\n"))
            .build(),
    )
    return FileSpec.builder(builder)
        .addFileComment("Generated by BuilderProcessor from %L. Do not edit.", target.simpleName)
        .addType(type.build())
        .build()
}

/** "Shape is an interface", "Van is an object". */
private fun describe(symbol: KSAnnotated): String {
    if (symbol !is KSClassDeclaration) return "$symbol is not a class"
    val kind = symbol.classKind.name.lowercase().replace('_', ' ')
    return "${symbol.simpleName.asString()} is ${if (kind.first() in "aeiou") "an" else "a"} $kind"
}
