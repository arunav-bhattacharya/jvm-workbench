package workbench.ksp.l02

import com.tschuchort.compiletesting.KotlinCompilation.ExitCode
import com.tschuchort.compiletesting.SourceFile
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import workbench.ksp.compileWithKsp

class InventoryProcessorTest {

    private val moveMate = SourceFile.kotlin(
        "MoveMate.kt",
        """
        package movemate

        import workbench.ksp.annotations.Inventory

        @Inventory
        data class Box(val label: String, val room: String, val weightGrams: Int, val fragile: Boolean = false)

        @Inventory
        data class Lamp(val name: String, val bulbs: Int, val shade: String?)

        @Inventory
        class Bookshelf(val shelves: Int, val books: List<String>)

        @Inventory
        data class Plant(val kind: String, val potLitres: Double, val waterEveryDays: Int = 7)
        """,
    )

    @Test
    fun `writes one card file per class, next to the class`() {
        val run = compileWithKsp(moveMate, processors = listOf(InventoryProcessorProvider()))

        // 1. the generated text, exactly
        assertThat(run.generated("movemate/LampInventoryCard.kt")).isEqualTo(
            """
            |// Generated by InventoryProcessor from Lamp. Do not edit.
            |package movemate
            |
            |fun Lamp.inventoryCard(): String =
            |    "Lamp: name=${'$'}name, bulbs=${'$'}bulbs, shade=${'$'}shade"
            |
            """.trimMargin(),
        )
        assertThat(run.generated.keys).containsExactlyInAnyOrder(
            "movemate/BoxInventoryCard.kt",
            "movemate/LampInventoryCard.kt",
            "movemate/BookshelfInventoryCard.kt",
            "movemate/PlantInventoryCard.kt",
        )
        // 2. the exit code: the generated files compiled together with MoveMate.kt
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        // 3. the messages: round 2 looks at the new card files and finds no sticky notes on them
        assertThat(run.messages)
            .contains("l02 round 1: @Inventory on [Box, Lamp, Bookshelf, Plant]")
            .contains("l02 round 2: @Inventory on []")
    }

    @Test
    fun `the cards are ordinary code that the rest of the program calls`() {
        val samples = SourceFile.kotlin(
            "Samples.kt",
            """
            package movemate

            fun boxCard() = Box("kitchen 1", "kitchen", 5200, fragile = true).inventoryCard()
            fun lampCard() = Lamp("desk lamp", 1, null).inventoryCard()
            fun bookshelfCard() = Bookshelf(3, listOf("atlas", "cookbook")).inventoryCard()
            fun plantCard() = Plant("fern", 2.5).inventoryCard()
            """,
        )

        val run = compileWithKsp(moveMate, samples, processors = listOf(InventoryProcessorProvider()))

        assertThat(run.generated("movemate/LampInventoryCard.kt")).isNotEmpty() // if missing: the list and messages
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        // 4. load and call the generated code through the result's class loader
        assertThat(run.callTopLevel("movemate.SamplesKt", "boxCard"))
            .isEqualTo("Box: label=kitchen 1, room=kitchen, weightGrams=5200, fragile=true")
        assertThat(run.callTopLevel("movemate.SamplesKt", "lampCard"))
            .isEqualTo("Lamp: name=desk lamp, bulbs=1, shade=null")
        assertThat(run.callTopLevel("movemate.SamplesKt", "bookshelfCard"))
            .isEqualTo("Bookshelf: shelves=3, books=[atlas, cookbook]")
        assertThat(run.callTopLevel("movemate.SamplesKt", "plantCard"))
            .isEqualTo("Plant: kind=fern, potLitres=2.5, waterEveryDays=7")
    }

    @Test
    fun `leaves out a constructor parameter that is not a property`() {
        val rug = SourceFile.kotlin(
            "Rug.kt",
            """
            package movemate

            import workbench.ksp.annotations.Inventory

            @Inventory
            class Rug(val colour: String, widthCm: Int) {
                val area = widthCm * 200
            }
            """,
        )

        val run = compileWithKsp(rug, processors = listOf(InventoryProcessorProvider()))

        assertThat(run.generated("movemate/RugInventoryCard.kt")).contains("\"Rug: colour=${'$'}colour\"")
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
    }

    @Test
    fun `reports an error on the line of an interface marked @Inventory`() {
        val shape = SourceFile.kotlin(
            "Shape.kt",
            """
            package movemate

            import workbench.ksp.annotations.Inventory

            @Inventory
            interface Shape
            """,
        )

        val run = compileWithKsp(shape, processors = listOf(InventoryProcessorProvider()))

        // the error names the file and the line of `interface Shape` (line 6), not of the @Inventory line
        assertThat(run.messages)
            .containsPattern("""e: \[ksp] \S*/Shape\.kt:6: @Inventory goes on a class, but Shape is an interface""")
        assertThat(run.exitCode).isEqualTo(ExitCode.COMPILATION_ERROR)
        assertThat(run.generated).isEmpty()
    }
}
