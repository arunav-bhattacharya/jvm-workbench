package workbench.ksp.l04

import com.tschuchort.compiletesting.KotlinCompilation.ExitCode
import com.tschuchort.compiletesting.SourceFile
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import workbench.ksp.compileWithKsp

class BuilderProcessorTest {

    private val moveMate = SourceFile.kotlin(
        "MoveMate.kt",
        """
        package movemate

        import workbench.ksp.annotations.Builder

        @Builder
        data class Box(val label: String, val room: String, val weightGrams: Int, val fragile: Boolean = false)

        @Builder
        data class Lamp(val name: String, val bulbs: Int, val shade: String?)

        @Builder
        class Bookshelf(val shelves: Int, val books: List<String>)

        @Builder
        data class Plant(val kind: String, val potLitres: Double, val waterEveryDays: Int = 7)

        // calls every builder the way an app would; the tests call these functions
        fun deskLamp() = LampBuilder().name("desk lamp").bulbs(1).shade(null).build().toString()
        fun plates() = BoxBuilder().label("plates").room("kitchen").weightGrams(4200).fragile(true).build().toString()
        fun shelf() = BookshelfBuilder().shelves(5).books(listOf("atlas", "cookbook")).build().books.toString()
        fun fern() = PlantBuilder().kind("fern").potLitres(2.5).waterEveryDays(3).build().toString()
        fun lampWithoutBulbs() = LampBuilder().name("desk lamp").build().toString()
        fun fernWithoutWater() = PlantBuilder().kind("fern").potLitres(2.5).build().toString()
        """,
    )

    @Test
    fun `generates LampBuilder with a field, a setter and build for each property`() {
        val run = compileWithKsp(moveMate, processors = listOf(BuilderProcessorProvider()))

        // 1. the generated text (checked first: if it is missing, the failure lists what was generated)
        assertThat(run.generated("movemate/LampBuilder.kt")).isEqualTo(
            """
            |// Generated by BuilderProcessor from Lamp. Do not edit.
            |package movemate
            |
            |import kotlin.Int
            |import kotlin.String
            |
            |public class LampBuilder {
            |  private var name: String? = null
            |
            |  private var bulbs: Int? = null
            |
            |  private var shade: String? = null
            |
            |  public fun name(name: String): LampBuilder {
            |    this.name = name
            |    return this
            |  }
            |
            |  public fun bulbs(bulbs: Int): LampBuilder {
            |    this.bulbs = bulbs
            |    return this
            |  }
            |
            |  public fun shade(shade: String?): LampBuilder {
            |    this.shade = shade
            |    return this
            |  }
            |
            |  public fun build(): Lamp = Lamp(
            |    name = name ?: error("LampBuilder: name was not set"),
            |    bulbs = bulbs ?: error("LampBuilder: bulbs was not set"),
            |    shade = shade,
            |  )
            |}
            |
            """.trimMargin(),
        )
        // 2. the exit code: the generated code compiles together with the code that calls it
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
    }

    @Test
    fun `the builders for every MoveMate class compile and build the right objects`() {
        val run = compileWithKsp(moveMate, processors = listOf(BuilderProcessorProvider()))

        assertThat(run.generated.keys).containsExactlyInAnyOrder(
            "movemate/BoxBuilder.kt", "movemate/LampBuilder.kt", "movemate/BookshelfBuilder.kt", "movemate/PlantBuilder.kt",
        )
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        // 3. call the generated code
        val file = "movemate.MoveMateKt"
        assertThat(run.callTopLevel(file, "deskLamp")).isEqualTo("Lamp(name=desk lamp, bulbs=1, shade=null)")
        assertThat(run.callTopLevel(file, "plates"))
            .isEqualTo("Box(label=plates, room=kitchen, weightGrams=4200, fragile=true)")
        assertThat(run.callTopLevel(file, "shelf")).isEqualTo("[atlas, cookbook]")
        assertThat(run.callTopLevel(file, "fern")).isEqualTo("Plant(kind=fern, potLitres=2.5, waterEveryDays=3)")
    }

    @Test
    fun `build stops with a clear message when a required property was never set`() {
        val run = compileWithKsp(moveMate, processors = listOf(BuilderProcessorProvider()))

        assertThat(run.generated("movemate/PlantBuilder.kt")).contains("public fun build(): Plant = Plant(")
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        // a parameter with a default is still required: KSP sees that a default exists, not what it is
        for ((function, message) in listOf(
            "lampWithoutBulbs" to "LampBuilder: bulbs was not set",
            "fernWithoutWater" to "PlantBuilder: waterEveryDays was not set",
        )) {
            val failure = runCatching { run.callTopLevel("movemate.MoveMateKt", function) }.exceptionOrNull()
            assertThat(failure?.cause).isInstanceOf(IllegalStateException::class.java).hasMessage(message)
        }
    }

    @Test
    fun `imports a type from another package, keeps nullable generics, and escapes keywords`() {
        val tricky = SourceFile.kotlin(
            "Tricky.kt",
            """
            package movemate.van

            import workbench.ksp.annotations.Builder
            import movemate.Box

            @Builder
            class Load(val first: Box, val spares: List<Box?>?)

            @Builder
            class Crate(val `in`: String, val `object`: String)

            fun load() = LoadBuilder().first(Box("plates")).spares(listOf(null, Box("cups"))).build().spares.toString()
            fun crate() = CrateBuilder().`in`("hall").`object`("mirror").build().let { it.`in` + "/" + it.`object` }
            """,
        )
        val box = SourceFile.kotlin("Box.kt", "package movemate\n\ndata class Box(val label: String)\n")

        val run = compileWithKsp(tricky, box, processors = listOf(BuilderProcessorProvider()))

        val load = run.generated("movemate/van/LoadBuilder.kt")
        assertThat(load).contains("import movemate.Box")
        assertThat(load).contains("  private var spares: List<Box?>? = null")
        assertThat(load).contains("  public fun spares(spares: List<Box?>?): LoadBuilder {")
        assertThat(load).contains("    first = first ?: error(\"LoadBuilder: first was not set\"),")
        val crate = run.generated("movemate/van/CrateBuilder.kt")
        assertThat(crate).contains("  private var `in`: String? = null")
        assertThat(crate).contains("  public fun `object`(`object`: String): CrateBuilder {")
        assertThat(crate).contains("    this.`in` = `in`")
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        assertThat(run.callTopLevel("movemate.van.TrickyKt", "load")).isEqualTo("[null, Box(label=cups)]")
        assertThat(run.callTopLevel("movemate.van.TrickyKt", "crate")).isEqualTo("hall/mirror")
    }

    @Test
    fun `a nested class gets a builder named after its outer class`() {
        val kitchen = SourceFile.kotlin(
            "Kitchen.kt",
            """
            package movemate

            import workbench.ksp.annotations.Builder

            class Kitchen {
                @Builder
                data class Drawer(val label: String, val handles: Int)
            }

            fun drawer() = KitchenDrawerBuilder().label("spoons").handles(2).build().toString()
            """,
        )

        val run = compileWithKsp(kitchen, processors = listOf(BuilderProcessorProvider()))

        val drawer = run.generated("movemate/KitchenDrawerBuilder.kt")
        assertThat(drawer).contains("public class KitchenDrawerBuilder {")
        assertThat(drawer).contains("public fun build(): Kitchen.Drawer = Kitchen.Drawer(")
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        assertThat(run.callTopLevel("movemate.KitchenKt", "drawer")).isEqualTo("Drawer(label=spoons, handles=2)")
    }
}
