package workbench.ksp.l06

import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.KSAnnotated
import com.tschuchort.compiletesting.KotlinCompilation.ExitCode
import com.tschuchort.compiletesting.SourceFile
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import workbench.ksp.compileWithKsp

class RoundsTest {

    private val moveMate = SourceFile.kotlin(
        "MoveMate.kt",
        """
        package movemate

        import workbench.ksp.annotations.Inventory
        import workbench.ksp.annotations.Moving

        @Moving
        data class Lamp(val name: String, val bulbs: Int, val shade: String?)

        @Inventory
        data class Box(val label: String, val room: String, val weightGrams: Int, val fragile: Boolean = false)

        // LampReceipt doesn't exist until round 1 has written it, so Van must wait for round 2
        @Moving
        data class Van(val plate: String, val lastLoad: LampReceipt)

        fun lampCard() = Lamp("desk lamp", 1, null).receipt("Ana").inventoryCard()
        fun vanCard() = Van("MV-1", Lamp("desk lamp", 1, null).receipt("Ana")).receipt("Ben").inventoryCard()
        fun boxCard() = Box("plates", "kitchen", 4200, fragile = true).inventoryCard()
        """,
    )

    // the receipts first, then the cards: the same order as the lesson's services file
    private val both = listOf(ReceiptProcessorProvider(), InventoryProcessorProvider())

    @Test
    fun `logs every round, from the first receipts to the last card`() {
        val run = compileWithKsp(moveMate, processors = both)

        val rounds = run.messages.lines().filter { it.startsWith("w: [ksp] [") }
        assertThat(rounds).containsExactly(
            "w: [ksp] [receipts] round 1: wrote [LampReceipt], set aside [Van]",
            "w: [ksp] [cards] round 1: wrote cards for [Box]",
            "w: [ksp] [receipts] round 2: wrote [VanReceipt], set aside []",
            "w: [ksp] [cards] round 2: wrote cards for [LampReceipt]",
            "w: [ksp] [receipts] round 3: wrote [], set aside []",
            "w: [ksp] [cards] round 3: wrote cards for [VanReceipt]",
            "w: [ksp] [receipts] round 4: wrote [], set aside []",
            "w: [ksp] [cards] round 4: wrote cards for []",
            "w: [ksp] [receipts] finish() after 4 rounds",
        )
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
    }

    @Test
    fun `a receipt is a data class annotated @Inventory, so it gets its own card one round later`() {
        val run = compileWithKsp(moveMate, processors = both)

        assertThat(run.generated("movemate/LampReceipt.kt")).isEqualTo(
            """
            |// Generated by ReceiptProcessor from Lamp. Do not edit.
            |package movemate
            |
            |import kotlin.Int
            |import kotlin.String
            |import workbench.ksp.annotations.Inventory
            |
            |@Inventory
            |public data class LampReceipt(
            |  public val name: String,
            |  public val bulbs: Int,
            |  public val shade: String?,
            |  public val signedBy: String,
            |)
            |
            |public fun Lamp.receipt(signedBy: String): LampReceipt = LampReceipt(name, bulbs, shade, signedBy)
            |
            """.trimMargin(),
        )
        assertThat(run.generated.keys).contains("movemate/LampReceiptInventoryCard.kt", "movemate/BoxInventoryCard.kt")
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        assertThat(run.callTopLevel("movemate.MoveMateKt", "lampCard"))
            .isEqualTo("LampReceipt: name=desk lamp, bulbs=1, shade=null, signedBy=Ana")
        assertThat(run.callTopLevel("movemate.MoveMateKt", "boxCard"))
            .isEqualTo("Box: label=plates, room=kitchen, weightGrams=4200, fragile=true")
    }

    @Test
    fun `a class that needs a type from round 1 is set aside, then written in round 2`() {
        val run = compileWithKsp(moveMate, processors = both)

        assertThat(run.generated("movemate/VanReceipt.kt")).contains("  public val lastLoad: LampReceipt,")
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        assertThat(run.callTopLevel("movemate.MoveMateKt", "vanCard")).isEqualTo(
            "VanReceipt: plate=MV-1, lastLoad=LampReceipt(name=desk lamp, bulbs=1, shade=null, signedBy=Ana), signedBy=Ben",
        )
    }

    @Test
    fun `reports a class that is still set aside when processing ends, on its own line`() {
        val trailer = SourceFile.kotlin(
            "Trailer.kt",
            """
            package movemate

            import workbench.ksp.annotations.Moving

            // nobody put @Moving on Piano, so no round will ever write PianoReceipt
            data class Piano(val keys: Int)

            @Moving
            data class Trailer(val plate: String, val load: PianoReceipt)
            """,
        )

        val run = compileWithKsp(trailer, processors = both)

        assertThat(run.messages).containsPattern(
            """e: \[ksp] \S*/Trailer\.kt:9: TrailerReceipt was never written: Trailer still needed PianoReceipt when processing ended after 1 round\. Check the spelling, or the annotation that should generate PianoReceipt\.""",
        )
        assertThat(run.exitCode).isEqualTo(ExitCode.COMPILATION_ERROR)
        assertThat(run.generated.keys).doesNotContain("movemate/TrailerReceipt.kt")
    }

    @Test
    fun `KSP 2_3_14 itself says nothing about a symbol that stays deferred, and the build passes`() {
        // a processor that sets every symbol aside, every round, and never complains
        val forever = SymbolProcessorProvider { env: SymbolProcessorEnvironment ->
            object : SymbolProcessor {
                var rounds = 0
                override fun process(resolver: Resolver): List<KSAnnotated> {
                    rounds++
                    return resolver.getSymbolsWithAnnotation("workbench.ksp.annotations.Moving").toList()
                }

                override fun finish() = env.logger.warn("finish() after $rounds round(s)")
            }
        }
        val lamp = SourceFile.kotlin(
            "Lamp.kt",
            """
            package movemate

            import workbench.ksp.annotations.Moving

            @Moving
            data class Lamp(val name: String, val bulbs: Int, val shade: String?)
            """,
        )

        val run = compileWithKsp(lamp, processors = listOf(forever))

        // the docs promise an error for each processor with deferred symbols left; 2.3.14 logs none
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        assertThat(run.messages).contains("w: [ksp] finish() after 1 round")
        assertThat(run.messages.lines().filter { it.startsWith("e:") }).isEmpty()
        assertThat(run.generated).isEmpty()
    }
}
