package workbench.ksp.l03

import com.tschuchort.compiletesting.KotlinCompilation.ExitCode
import com.tschuchort.compiletesting.SourceFile
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import workbench.ksp.KspResult
import workbench.ksp.compileWithKsp

class LabelProcessorTest {

    /** Reads a `const val` from a generated label object through the result's class loader. */
    private fun KspResult.label(objectName: String, constant: String): Any? =
        loadClass("movemate.$objectName").getField(constant).get(null)

    @Test
    fun `prints the typed shape of each MoveMate class`() {
        val moveMate = SourceFile.kotlin(
            "MoveMate.kt",
            """
            package movemate

            import workbench.ksp.annotations.Fragile
            import workbench.ksp.annotations.Label

            @Label
            data class Lamp(val name: String, val bulbs: Int, val shade: String?)

            @Label
            class Bookshelf(val shelves: Int, val books: List<String>)

            @Label
            data class Plant(val kind: String, val potLitres: Double, val waterEveryDays: Int = 7)

            @Label
            class Mirror(val widthCm: Int, val heightCm: Int, @Fragile val glass: String)
            """,
        )

        val run = compileWithKsp(moveMate, processors = listOf(LabelProcessorProvider()))

        // 1. the generated text
        assertThat(run.generated("movemate/LampLabel.kt")).isEqualTo(
            """
            |// Generated by LabelProcessor from Lamp. Do not edit.
            |package movemate
            |
            |object LampLabel {
            |    const val SHAPE: String = "Lamp(name: String, bulbs: Int, shade: String?)"
            |}
            |
            """.trimMargin(),
        )
        // 2. the exit code
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        // 3. call the generated code: nullable, generic, a default KSP can't read, a @Fragile parameter
        assertThat(run.label("LampLabel", "SHAPE")).isEqualTo("Lamp(name: String, bulbs: Int, shade: String?)")
        assertThat(run.label("BookshelfLabel", "SHAPE")).isEqualTo("Bookshelf(shelves: Int, books: List<String>)")
        assertThat(run.label("PlantLabel", "SHAPE"))
            .isEqualTo("Plant(kind: String, potLitres: Double, waterEveryDays: Int = ...)")
        assertThat(run.label("MirrorLabel", "SHAPE"))
            .isEqualTo("Mirror(widthCm: Int, heightCm: Int, @Fragile glass: String)")
    }

    @Test
    fun `prints tricky types correctly, all the way down`() {
        val crate = SourceFile.kotlin(
            "Crate.kt",
            """
            package movemate

            import workbench.ksp.annotations.Label

            typealias Litres = Double

            @Label
            class Crate(val sizes: Map<String, List<Int?>>?, val water: Litres, val odds: List<*>, val spare: Crate?)
            """,
        )

        val run = compileWithKsp(crate, processors = listOf(LabelProcessorProvider()))

        assertThat(run.generated("movemate/CrateLabel.kt")).isNotEmpty() // if missing: the list and messages
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        assertThat(run.label("CrateLabel", "SHAPE"))
            .isEqualTo("Crate(sizes: Map<String, List<Int?>>?, water: Litres, odds: List<*>, spare: Crate?)")
    }

    @Test
    fun `reads a Java class in the same module, with its platform types`() {
        val javaCrate = SourceFile.java(
            "MovingCrate.java",
            """
            package movemate;

            import workbench.ksp.annotations.Label;

            @Label
            public class MovingCrate {
                private final String label;
                private final int weightGrams;

                public MovingCrate(String label, int weightGrams) {
                    this.label = label;
                    this.weightGrams = weightGrams;
                }
            }
            """,
        )

        val run = compileWithKsp(javaCrate, processors = listOf(LabelProcessorProvider()))

        assertThat(run.generated("movemate/MovingCrateLabel.kt")).isNotEmpty()
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        // Java has no primary constructor, and a Java String may or may not be null: String!
        assertThat(run.label("MovingCrateLabel", "SHAPE")).isEqualTo("MovingCrate(label: String!, weightGrams: Int)")
    }

    @Test
    fun `reads @Room and @Handling arguments, and marks the defaults`() {
        val rooms = SourceFile.kotlin(
            "Rooms.kt",
            """
            package movemate

            import workbench.ksp.annotations.Label
            import workbench.ksp.annotations.Room
            import workbench.ksp.annotations.l03.Care
            import workbench.ksp.annotations.l03.Handling

            @Label
            data class Lamp(val name: String, val bulbs: Int, val shade: String?)

            @Label @Room("study") @Handling(care = Care.UPRIGHT, packWith = Lamp::class, stackable = false)
            class Bookshelf(val shelves: Int, val books: List<String>)

            @Label @Room("conservatory") @Handling(stackable = false)
            data class Plant(val kind: String, val potLitres: Double, val waterEveryDays: Int = 7)
            """,
        )

        val run = compileWithKsp(rooms, processors = listOf(LabelProcessorProvider()))

        assertThat(run.generated("movemate/BookshelfLabel.kt"))
            .contains("    const val ROOM: String = \"study\"")
        assertThat(run.exitCode).isEqualTo(ExitCode.OK)
        assertThat(run.label("BookshelfLabel", "HANDLING")).isEqualTo("care=UPRIGHT, stackable=false, packWith=Lamp")
        assertThat(run.label("PlantLabel", "ROOM")).isEqualTo("conservatory")
        assertThat(run.label("PlantLabel", "HANDLING"))
            .isEqualTo("care=NORMAL (default), stackable=false, packWith=Any (default)")
        // no @Room and no @Handling: no ROOM or HANDLING line at all
        assertThat(run.generated("movemate/LampLabel.kt")).doesNotContain("ROOM", "HANDLING")
    }

    @Test
    fun `reports an error on the line of an object marked @Label`() {
        val truck = SourceFile.kotlin(
            "Truck.kt",
            """
            package movemate

            import workbench.ksp.annotations.Label

            @Label
            object Truck
            """,
        )

        val run = compileWithKsp(truck, processors = listOf(LabelProcessorProvider()))

        assertThat(run.messages).containsPattern("""e: \[ksp] \S*/Truck\.kt:6: @Label goes on a class, but Truck is an object""")
        assertThat(run.exitCode).isEqualTo(ExitCode.COMPILATION_ERROR)
    }
}
