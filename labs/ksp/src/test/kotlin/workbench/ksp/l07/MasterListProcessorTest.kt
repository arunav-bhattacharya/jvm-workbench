package workbench.ksp.l07

import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.KSAnnotated
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.tschuchort.compiletesting.KotlinCompilation.ExitCode
import com.tschuchort.compiletesting.SourceFile
import java.lang.reflect.InvocationTargetException
import org.assertj.core.api.Assertions.assertThat
import org.assertj.core.api.Assertions.assertThatThrownBy
import org.junit.jupiter.api.Test
import workbench.ksp.KspResult
import workbench.ksp.compileWithKsp

class MasterListProcessorTest {

    // two files, two classes each, so the list must gather symbols from more than one file
    private val lampAndPlant = SourceFile.kotlin(
        "Lamp.kt",
        """
        package movemate

        import workbench.ksp.annotations.Inventory

        @Inventory
        data class Lamp(val name: String, val bulbs: Int, val shade: String?)

        @Inventory
        data class Plant(val kind: String, val potLitres: Double, val waterEveryDays: Int = 7)
        """,
    )
    private val boxAndShelf = SourceFile.kotlin(
        "Box.kt",
        """
        package movemate

        import workbench.ksp.annotations.Inventory

        @Inventory
        data class Box(val label: String, val room: String, val weightGrams: Int, val fragile: Boolean = false)

        @Inventory
        class Bookshelf(val shelves: Int, val books: List<String>)
        """,
    )
    private val jobSheet = mapOf(LIST_NAME to "MovingDayList")

    private fun KspResult.listObject(className: String): Any = loadClass(className).getField("INSTANCE").get(null)

    @Test
    fun `writes one master list of every @Inventory class, sorted by name`() {
        val run = compileWithKsp(lampAndPlant, boxAndShelf, processors = listOf(MasterListProcessorProvider()), options = jobSheet)

        // 1. the exit code: OK also proves the list was written once, though KSP ran a second round
        assertThat(run.exitCode).describedAs(run.messages).isEqualTo(ExitCode.OK)
        // 2. the generated text
        assertThat(run.generated("movemate/MovingDayList.kt")).isEqualTo(
            """
            |// Generated by MasterListProcessor from 4 classes. Do not edit.
            |package movemate
            |
            |import kotlin.Any
            |import kotlin.String
            |import kotlin.collections.List
            |
            |public object MovingDayList {
            |  public val names: List<String> = listOf("Bookshelf", "Box", "Lamp", "Plant")
            |
            |  public fun cardFor(thing: Any): String = when (thing) {
            |    is Bookshelf -> thing.inventoryCard()
            |    is Box -> thing.inventoryCard()
            |    is Lamp -> thing.inventoryCard()
            |    is Plant -> thing.inventoryCard()
            |    else -> error("MovingDayList has no card for ${'$'}{thing::class.simpleName}")
            |  }
            |}
            |
            """.trimMargin(),
        )
        // 3. call the generated code through the result's class loader
        val list = run.listObject("movemate.MovingDayList")
        assertThat(list.javaClass.getMethod("getNames").invoke(list)).isEqualTo(listOf("Bookshelf", "Box", "Lamp", "Plant"))
        val lamp = run.loadClass("movemate.Lamp")
            .getConstructor(String::class.java, Int::class.java, String::class.java)
            .newInstance("desk lamp", 1, null)
        val cardFor = list.javaClass.getMethod("cardFor", Any::class.java)
        assertThat(cardFor.invoke(list, lamp)).isEqualTo("Lamp: name=desk lamp, bulbs=1, shade=null")
        // something that is not on the list fails loudly, by name
        assertThatThrownBy { cardFor.invoke(list, "a sofa") }
            .isInstanceOf(InvocationTargetException::class.java)
            .cause().isInstanceOf(IllegalStateException::class.java).hasMessage("MovingDayList has no card for String")
    }

    @Test
    fun `the options name the list and choose its package`() {
        val run = compileWithKsp(
            lampAndPlant, boxAndShelf,
            processors = listOf(MasterListProcessorProvider()),
            options = mapOf(LIST_NAME to "PackingList", LIST_PACKAGE to "movemate.lists"),
        )

        assertThat(run.exitCode).describedAs(run.messages).isEqualTo(ExitCode.OK)
        val text = run.generated("movemate/lists/PackingList.kt")
        assertThat(text)
            .contains("package movemate.lists")
            .contains("import movemate.Lamp")
            .contains("import movemate.inventoryCard")
            .contains("public object PackingList {")
        assertThat(run.generated.keys).doesNotContain("movemate/MovingDayList.kt")
    }

    @Test
    fun `a missing movemate listName is an error that says how to fix it`() {
        val run = compileWithKsp(lampAndPlant, processors = listOf(MasterListProcessorProvider()))

        assertThat(run.exitCode).describedAs(run.messages).isEqualTo(ExitCode.COMPILATION_ERROR)
        assertThat(run.messages).contains(
            "e: [ksp] MasterListProcessor needs the processor option movemate.listName, the name of the list it generates. " +
                "Add ksp { arg(\"movemate.listName\", \"MovingDayList\") } to the build file.",
        )
        assertThat(run.generated).isEmpty()
    }

    @Test
    fun `a listName that is not a class name is an error`() {
        val run = compileWithKsp(
            lampAndPlant,
            processors = listOf(MasterListProcessorProvider()),
            options = mapOf(LIST_NAME to "moving-day"),
        )

        assertThat(run.exitCode).describedAs(run.messages).isEqualTo(ExitCode.COMPILATION_ERROR)
        assertThat(run.messages)
            .contains("e: [ksp] movemate.listName must be a class name such as MovingDayList, but it is 'moving-day'")
        assertThat(run.generated).isEmpty()
    }

    @Test
    fun `the list is an aggregating output that names the file of every class on it`() {
        // kctfork can't run an incremental build, so this test asks listDependencies directly, from inside a
        // tiny processor of its own, and prints what it returned
        val run = compileWithKsp(lampAndPlant, boxAndShelf, processors = listOf(DependencySpyProvider()))

        assertThat(run.messages).contains("w: [ksp] aggregating=true allFiles=false files=[Box.kt, Lamp.kt]")
    }
}

/** Test helper: finds the @Inventory classes, calls [listDependencies] and logs what came back. */
class DependencySpyProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor = object : SymbolProcessor {
        override val apiFeatures = com.google.devtools.ksp.buildApiFeatures {
            enableBackingFields = true
            enableContextParameters = true
        }

        override fun process(resolver: Resolver): List<KSAnnotated> {
            val classes = resolver.getSymbolsWithAnnotation("workbench.ksp.annotations.Inventory")
                .filterIsInstance<KSClassDeclaration>().toList()
            if (classes.isNotEmpty()) {
                val d = try {
                    listDependencies(classes)
                } catch (e: NotImplementedError) {
                    environment.logger.warn("listDependencies is not done yet: ${e.message}")
                    return emptyList()
                }
                environment.logger.warn(
                    "aggregating=${d.aggregating} allFiles=${d.isAllSources} " +
                        "files=${d.originatingFiles.map { it.fileName }.sorted()}",
                )
            }
            return emptyList()
        }
    }
}
