// Smoke example (keep or delete). It proves the pipeline: kctfork tests, a demo, and the real build in
// :injector:app. It is complete in src/main too, so `test` and `solutionTest` both pass on a fresh checkout.

/** Registered in workbench/injector/smoke/SymbolProcessorProvider. */
class FactoryProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        FactoryProcessor(environment.codeGenerator, environment.logger)
}

/** For each class annotated [Factory], generates `object <ClassName>Factory { fun create(): <ClassName> }`. */
class FactoryProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
) : SymbolProcessor {

    override val apiFeatures: ApiFeatures = buildApiFeatures {
        enableBackingFields = true
        enableContextParameters = true
    }

    override fun process(resolver: Resolver): List<KSAnnotated> {
        val (ready, later) = resolver.getSymbolsWithAnnotation(Factory::class.qualifiedName!!).toList()
            .partition { it.validate(apiFeatures = apiFeatures) }
        for (cls in ready.filterIsInstance<KSClassDeclaration>()) {
            if (cls.classKind != ClassKind.CLASS) {
                logger.error("@Factory needs a class it can construct, but ${cls.simpleName.asString()} is not one", cls)
                continue
            }
            // the smoke factory can't inject anything yet: point at the first parameter it can't supply
            val parameter = cls.primaryConstructor?.parameters?.firstOrNull()
            if (parameter != null) {
                logger.error(
                    "${cls.simpleName.asString()} needs a ${parameter.name?.asString()}, and the smoke factory " +
                        "only builds classes whose constructor takes no parameters",
                    parameter,
                )
                continue
            }
            factoryFile(cls).writeTo(codeGenerator, Dependencies(aggregating = false, cls.containingFile!!))
        }
        return later
    }
}

/** `<package>/<ClassName>Factory.kt` with `public object <ClassName>Factory { public fun create(): <ClassName> }`. */
fun factoryFile(cls: KSClassDeclaration): FileSpec {
    val type = cls.toClassName()
    val factory = TypeSpec.objectBuilder("${type.simpleName}Factory")
        .addFunction(FunSpec.builder("create").returns(type).addStatement("return %T()", type).build())
        .build()
    return FileSpec.builder(type.packageName, "${type.simpleName}Factory")
        .addFileComment("Generated by FactoryProcessor from %L. Do not edit.", type.simpleName)
        .addType(factory)
        .build()
}
