package workbench.injector.l01

import com.tschuchort.compiletesting.KotlinCompilation.ExitCode
import com.tschuchort.compiletesting.SourceFile
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import workbench.injector.compileWithKsp

class ComponentTest {

    private val both = listOf(FactoryProcessorProvider(), ComponentProcessorProvider())

    @Test
    fun `writes the plan in creation order, singletons as vals and the rest as new functions`() {
        val run = compileWithKsp(*MoveMateSources.all, processors = both)

        assertThat(run.exitCode).withFailMessage(run.messages).isEqualTo(ExitCode.OK)
        assertThat(run.generated("movemate/GeneratedMovingDayComponent.kt")).isEqualTo(
            """
            |// Generated by ComponentProcessor from MovingDayComponent. Do not edit.
            |package movemate
            |
            |public class GeneratedMovingDayComponent : MovingDayComponent {
            |  private val route: Route = RouteFactory.create()
            |
            |  private val driver: Driver = DriverFactory.create(route)
            |
            |  private val truck: Truck = TruckFactory.create(driver)
            |
            |  private val crew: Crew = CrewFactory.create(truck, newPacker(), newPacker())
            |
            |  private val movingDay: MovingDay = MovingDayFactory.create(crew, route)
            |
            |  private fun newTapeRoll(): TapeRoll = TapeRollFactory.create()
            |
            |  private fun newPacker(): Packer = PackerFactory.create(newTapeRoll())
            |
            |  override fun movingDay(): MovingDay = movingDay
            |
            |  override fun truck(): Truck = truck
            |}
            |
            """.trimMargin(),
        )
    }

    @Test
    fun `the generated component shares the singletons and gives each packer a new tape roll`() {
        val check = SourceFile.kotlin(
            "Check.kt",
            """
            package movemate

            fun check(): String {
                val plan = GeneratedMovingDayComponent()
                val day = plan.movingDay()
                val crew = day.crew
                return listOf(
                    "one truck: " + (crew.truck === plan.truck()),
                    "one route: " + (day.route === crew.truck.driver.route),
                    "two tape rolls: " + (crew.kitchenPacker.tape !== crew.bedroomPacker.tape),
                    "same day twice: " + (plan.movingDay() === day),
                    "rolls made: " + TapeRoll.made,
                ).joinToString()
            }
            """,
        )

        val run = compileWithKsp(*MoveMateSources.all, check, processors = both)

        assertThat(run.exitCode).withFailMessage(run.messages).isEqualTo(ExitCode.OK)
        assertThat(run.callTopLevel("movemate.CheckKt", "check"))
            .isEqualTo("one truck: true, one route: true, two tape rolls: true, same day twice: true, rolls made: 2")
    }

    @Test
    fun `reports a missing binding on the parameter that asks for it`() {
        val driverWithoutInject = SourceFile.kotlin(
            "Driver.kt",
            """
            package movemate

            class Driver(val route: Route)
            """,
        )
        val sources = MoveMateSources.all.map { if (it == MoveMateSources.driver) driverWithoutInject else it }

        val run = compileWithKsp(*sources.toTypedArray(), processors = both)

        // Truck.kt line 8 is `val driver: Driver,`: the request that nobody can answer
        assertThat(run.exitCode).isEqualTo(ExitCode.COMPILATION_ERROR)
        assertThat(run.messages).containsPattern(
            """e: \[ksp] \S*/Truck\.kt:8: Truck needs Driver, but nobody provides Driver\. Add @Inject to its constructor\.""",
        )
        assertThat(run.generated).doesNotContainKey("movemate/GeneratedMovingDayComponent.kt")
    }

    @Test
    fun `refuses a component that is not an interface`() {
        val component = SourceFile.kotlin(
            "MovingDayComponent.kt",
            """
            package movemate

            import workbench.injector.annotations.Component

            @Component
            abstract class MovingDayComponent {
                abstract fun movingDay(): MovingDay
            }
            """,
        )
        val sources = MoveMateSources.all.map { if (it == MoveMateSources.component) component else it }

        val run = compileWithKsp(*sources.toTypedArray(), processors = both)

        assertThat(run.exitCode).isEqualTo(ExitCode.COMPILATION_ERROR)
        assertThat(run.messages).containsPattern(
            """e: \[ksp] \S*/MovingDayComponent\.kt:6: @Component goes on an interface that lists what the app asks for, but MovingDayComponent is not an interface""",
        )
    }
}
