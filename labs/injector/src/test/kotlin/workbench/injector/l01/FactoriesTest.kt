package workbench.injector.l01

import com.tschuchort.compiletesting.KotlinCompilation.ExitCode
import com.tschuchort.compiletesting.SourceFile
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import workbench.injector.compileWithKsp

class FactoriesTest {

    @Test
    fun `writes one factory per @Inject class, taking what the constructor takes`() {
        val run = compileWithKsp(MoveMateSources.route, MoveMateSources.driver, processors = listOf(FactoryProcessorProvider()))

        assertThat(run.exitCode).withFailMessage(run.messages).isEqualTo(ExitCode.OK)
        assertThat(run.generated("movemate/DriverFactory.kt")).isEqualTo(
            """
            |// Generated by FactoryProcessor from Driver. Do not edit.
            |package movemate
            |
            |public object DriverFactory {
            |  public fun create(route: Route): Driver = Driver(route)
            |}
            |
            """.trimMargin(),
        )
        assertThat(run.generated("movemate/RouteFactory.kt")).contains("public fun create(): Route = Route()")
        // call the generated code: RouteFactory.create(), then DriverFactory.create(route)
        val route = run.callOnObject("movemate.RouteFactory", "create")
        val factory = run.loadClass("movemate.DriverFactory")
        val driver = factory.getMethod("create", run.loadClass("movemate.Route"))
            .invoke(factory.getField("INSTANCE").get(null), route)
        assertThat(driver.javaClass.getMethod("getRoute").invoke(driver)).isSameAs(route)
    }

    @Test
    fun `@Inject on the class means its primary constructor`() {
        val run = compileWithKsp(MoveMateSources.tapeRoll, MoveMateSources.packer, processors = listOf(FactoryProcessorProvider()))

        assertThat(run.exitCode).withFailMessage(run.messages).isEqualTo(ExitCode.OK)
        assertThat(run.generated("movemate/PackerFactory.kt"))
            .contains("public object PackerFactory {", "public fun create(tape: TapeRoll): Packer = Packer(tape)")
    }

    @Test
    fun `reports an error on the line of an interface marked @Inject`() {
        val shape = SourceFile.kotlin(
            "Shape.kt",
            """
            package movemate

            import workbench.injector.annotations.Inject

            @Inject
            interface Shape
            """,
        )

        val run = compileWithKsp(shape, processors = listOf(FactoryProcessorProvider()))

        // line 6 is `interface Shape`: KSP points at the declaration, not at the @Inject line
        assertThat(run.exitCode).isEqualTo(ExitCode.COMPILATION_ERROR)
        assertThat(run.messages)
            .containsPattern("""e: \[ksp] \S*/Shape\.kt:6: @Inject goes on a class the plan can build, but Shape is an interface""")
        assertThat(run.generated).isEmpty()
    }
}
