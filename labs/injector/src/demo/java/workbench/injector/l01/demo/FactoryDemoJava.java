package workbench.injector.l01.demo;

import java.io.IOException;
import java.io.Writer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Set;
import java.util.stream.Stream;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.VariableElement;
import javax.tools.Diagnostic;
import javax.tools.JavaCompiler;
import javax.tools.JavaFileObject;
import javax.tools.SimpleJavaFileObject;
import javax.tools.StandardJavaFileManager;
import javax.tools.StandardLocation;
import javax.tools.ToolProvider;
import workbench.injector.annotations.Inject;

// The closest Java equivalent: a javac annotation processor that writes the same factories for Java classes.
// main() runs javac in memory with the processor on three small Java classes and prints what it wrote.
//   ./gradlew :injector:demo -Pmain=workbench.injector.l01.demo.FactoryDemoJava
public class FactoryDemoJava {

    /** For each @Inject constructor, writes <Name>Factory.java with a static create() that calls it. */
    @SupportedAnnotationTypes("workbench.injector.annotations.Inject")
    public static class FactoryAnnotationProcessor extends AbstractProcessor {

        @Override
        public SourceVersion getSupportedSourceVersion() {
            return SourceVersion.latestSupported();
        }

        @Override
        public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment round) {
            for (Element element : round.getElementsAnnotatedWith(Inject.class)) {          // 1. Find
                if (element.getKind() != ElementKind.CONSTRUCTOR) {                           // 2. Check
                    processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR,
                            "put @Inject on the constructor the plan should call", element);
                    continue;
                }
                ExecutableElement constructor = (ExecutableElement) element;
                TypeElement type = (TypeElement) constructor.getEnclosingElement();
                String pkg = processingEnv.getElementUtils().getPackageOf(type).getQualifiedName().toString();
                String name = type.getSimpleName().toString();
                List<String> parameters = new ArrayList<>();
                List<String> arguments = new ArrayList<>();
                for (VariableElement p : constructor.getParameters()) {                       // 3. Read
                    parameters.add(p.asType() + " " + p.getSimpleName());
                    arguments.add(p.getSimpleName().toString());
                }
                String source = """
                        // Generated by FactoryAnnotationProcessor from %2$s. Do not edit.
                        package %1$s;

                        public final class %2$sFactory {
                            private %2$sFactory() {}

                            public static %2$s create(%3$s) {
                                return new %2$s(%4$s);
                            }
                        }
                        """.formatted(pkg, name, String.join(", ", parameters), String.join(", ", arguments));
                try (Writer out = processingEnv.getFiler()                                    // 4. Write
                        .createSourceFile(pkg + "." + name + "Factory", type).openWriter()) {
                    out.write(source);
                } catch (IOException e) {
                    processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, e.toString(), type);
                }
            }
            return true;
        }
    }

    public static void main(String[] args) throws IOException {
        Path root = Path.of("build/javac-demo/l01");
        deleteTree(root);
        Path generated = Files.createDirectories(root.resolve("generated"));
        Path classes = Files.createDirectories(root.resolve("classes"));

        List<JavaFileObject> sources = List.of(
                source("Route", "public class Route { @Inject public Route() {} }"),
                source("Driver", "public class Driver { @Inject public Driver(Route route) {} }"),
                source("Truck", "public class Truck { @Inject public Truck(Driver driver) {} }"));

        JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
        try (StandardJavaFileManager files = javac.getStandardFileManager(null, null, null)) {
            files.setLocationFromPaths(StandardLocation.SOURCE_OUTPUT, List.of(generated));
            files.setLocationFromPaths(StandardLocation.CLASS_OUTPUT, List.of(classes));
            JavaCompiler.CompilationTask task = javac.getTask(null, files, null,
                    List.of("-classpath", System.getProperty("java.class.path")), null, sources);
            task.setProcessors(List.of(new FactoryAnnotationProcessor()));   // passed directly, like kctfork's providers
            System.out.println("javac succeeded: " + task.call());
        }
        try (Stream<Path> found = Files.walk(generated)) {
            for (Path file : found.filter(Files::isRegularFile).sorted().toList()) {
                System.out.println("--- " + generated.relativize(file).toString().replace('\\', '/'));
                System.out.print(Files.readString(file));
            }
        }
    }

    private static JavaFileObject source(String name, String body) {
        String text = "package movemate;\n\nimport workbench.injector.annotations.Inject;\n\n" + body + "\n";
        return new SimpleJavaFileObject(Path.of("movemate", name + ".java").toUri(), JavaFileObject.Kind.SOURCE) {
            @Override
            public CharSequence getCharContent(boolean ignoreEncodingErrors) {
                return text;
            }
        };
    }

    private static void deleteTree(Path root) throws IOException {
        if (!Files.exists(root)) return;
        try (Stream<Path> all = Files.walk(root)) {
            for (Path p : all.sorted(Comparator.reverseOrder()).toList()) Files.delete(p);
        }
    }
}
